"""Elliptic CurveGroup class and functions.

CurveGroup is every point of the curve, a group that needs be neither
cyclic nor of prime order. Curve, in the btclib.curves.curve module, is
the cyclic subgroup of prime order generated by G, which is the group
everything built on curves multiplies in; the two are the whole of the
hierarchy, and the class docstring of Curve says what separates them.
"""

