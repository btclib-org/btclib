HEX_THRESHOLD = 0xFFFFFFFF


def _is_prime(x: int) -> bool:
    """Return True if x is an odd prime, to a Fermat base-2 test.

    Probabilistic is enough for the two numbers this is asked about, a
    curve's p and the order n of its subgroup: both are parameters a
    caller states rather than numbers the library searches for, so a
    base-2 Fermat liar there is a number somebody picked to be one, and a
    curve built to lie about its own parameters is not what a primality
    test defends against.

    Two answers False, being even, and neither caller wants it otherwise:
    the short Weierstrass equation defines no curve in characteristic 2,
    and a subgroup of order 2 holds one point besides infinity.

    Private, and out of btclib.number_theory: one Fermat base is not the
    primality test a caller reading that module would take it for.
    """
    return x >= 2 and x % 2 != 0 and pow(2, x - 1, x) == 1


def _jac_from_aff(Q: Point) -> JacPoint:
    """Return the Jacobian representation of the affine point.

    The input point is assumed to be on curve.
    """
    return Q[0], Q[1], 1 if Q[1] else 0


def _blinded_jac(Q: JacPoint, ec: CurveGroup) -> JacPoint:
    """Return the same point with a Z nobody can predict.

    A Jacobian point has a coordinate more than the curve needs: (X, Y, Z)
    and (l^2*X, l^3*Y, l*Z) are the same affine point for every nonzero l.
    Spending that freedom on a random l is what libsecp256k1's
    `secp256k1_ecmult_gen` does with `secp256k1_gej_rescale`, so that the
    values a multiplication forms are not a function of the scalar alone:
    without it the same scalar produces the same integers on every call
    and in every process, and a table of them can be built offline.

    It is not what makes a multiplication constant-time and does not
    claim to be -- SECURITY.md publishes the Python path as
    variable-time, and the recodings of curve_group_2 are what address
    the duration. This addresses the values.

    Three multiplications and a random field element, against the ~2500
    multiplications of the multiplication it precedes. Infinity comes
    back infinity, Z == 0 scaling to Z == 0.
    """
    p = ec.p
    # a nonzero l: zero would send the point to infinity, which is the one
    # value of l that is not an isomorphism
    lam = 1 + secrets.randbelow(p - 1)
    lam2 = lam * lam % p
    return Q[0] * lam2 % p, Q[1] * lam2 % p * lam % p, Q[2] * lam % p


class CurveGroup:
    """Finite group of the points of an elliptic curve over Fp.

    The elliptic curve is the set of points (x, y) that are solutions to
    a Weierstrass equation y^2 = x^3 + a*x + b, with x, y, a, and b in
    Fp (p being a prime), together with a point at infinity INF. The
    constants a, b must satisfy the relationship 4 a^3 + 27 b^2 ≠ 0.

    The group is defined by the point addition group law, INF being its
    neutral element, and it is finite and abelian — hence a product of at
    most two cyclic groups, Z_n1 x Z_n2 with n2 dividing n1, so neither
    cyclic nor of prime order in general.

    How many points it holds is not among its data, and cannot be
    computed from them: the order is p+1 minus the trace of Frobenius,
    which Hasse's theorem bounds by twice the square root of p and
    nothing here counts. Nor is any point of the group distinguished from
    the others. The generator G, the prime order n of the cyclic subgroup
    it generates, and the cofactor relating that n to the order of this
    group are the parameters of Curve, in btclib.curves.curve, which is
    what a caller of the library multiplies in; what this class is for is
    the arithmetic underneath, shared by the two and defined by p, a and b
    alone.
    """

    def __init__(self, p: Integer, a: Integer, b: Integer) -> None:
        # Parameters are checked according to SEC 1 v.2 3.1.1.2.1
        p = int_from_integer(p)
        a = int_from_integer(a)
        b = int_from_integer(b)

        # 1) check that p is a prime
        if not _is_prime(p):
            err_msg = "p is not prime: "
            err_msg += f"'{hex_string(p)}'" if p > HEX_THRESHOLD else f"{p}"
            raise BTClibValueError(err_msg)

        plen = p.bit_length()
        # byte-length
        self.p_size = ceil(plen / 8)
        # must be true to break symmetry using quadratic residue
        self.p_is_3_mod_4 = p % 4 == 3
        self.p = p

        # how many bits a scalar of this group has, which is what fixes
        # the digit count of _mult_regular_window below -- the quantity a
        # loop running once per digit of the scalar in hand puts on the
        # clock. Hasse bounds the order of the group by p + 1 + 2*sqrt(p),
        # so a scalar reduced mod that order is under 2^(plen+1); Curve
        # narrows it to nlen, the order of its subgroup being the bound
        # there. It is a count and not a limit: a scalar above it is
        # multiplied all the same, in the digits it needs
        self.scalar_len = plen + 1

        # 2. check that a and b are integers in [0, p−1]  # noqa: RUF003
        if a < 0:
            raise BTClibValueError(f"negative a: {a}")
        if p <= a:
            err_msg = "p <= a: " + (
                f"'{hex_string(p)}' <= '{hex_string(a)}'"
                if p > HEX_THRESHOLD
                else f"{p} <= {a}"
            )
            raise BTClibValueError(err_msg)
        if b < 0:
            raise BTClibValueError(f"negative b: {b}")
        if p <= b:
            err_msg = "p <= b: " + (
                f"'{hex_string(p)}' <= '{hex_string(b)}'"
                if p > HEX_THRESHOLD
                else f"{p} <= {b}"
            )
            raise BTClibValueError(err_msg)

        # 3. Check that 4*a^3 + 27*b^2 ≠ 0 (mod p)
        d = 4 * a * a * a + 27 * b * b
        if d % p == 0:
            raise BTClibValueError("zero discriminant")
        self._a = a
        self._b = b
        # which spelling of the tangent law _double_jac_helper runs. The
        # curve decides it and a curve does not change, so it is decided
        # here rather than by a test inside the function a multiplication
        # calls 253 times: the a*Z^4 term is zero for the k1 family, and
        # for the a == p - 3 of most catalogued curves it is a difference
        # of two squares that costs one product instead of three
        self._a_is_zero = a == 0
        self._a_is_minus_3 = a == p - 3
        # what add_jac feeds its formula in place of an operand at
        # infinity: any value does, the arithmetic on it being thrown
        # away, as long as it is the size of a real coordinate -- which is
        # the whole of what it is for, so a fraction of p rather than a
        # small constant. On a curve whose p is a handful of bits some of
        # these are zero, and nothing there is worth timing anyway
        self._stand_in_q = p // 3, p // 5, p // 7
        self._stand_in_r = p // 11, p // 13, p // 17
        # the points whose wNAF table is worth memoizing rather than
        # rebuilding per call: the ones the curve itself names, which a
        # verification hands the same on every call. A CurveGroup names
        # none -- it has no generator -- and Curve fills this in
        self._fixed_points: frozenset[JacPoint] = frozenset()

    @override
    def __str__(self) -> str:
        # the class name, not the literal "Curve": the two classes hold
        # different parameters, so a CurveGroup announcing itself as a
        # Curve reads as a curve whose G and n went missing -- and the
        # repr below, which is meant to eval back to an equal object,
        # would name a constructor four arguments short
        result = type(self).__name__
        if self.p > HEX_THRESHOLD:
            result += f"\n p   = {hex_string(self.p)}"
        else:
            result += f"\n p   = {self.p}"

        if self._a > HEX_THRESHOLD or self._b > HEX_THRESHOLD:
            result += f"\n a   = {hex_string(self._a)}"
            result += f"\n b   = {hex_string(self._b)}"
        else:
            result += f"\n a   = {self._a}"
            result += f"\n b   = {self._b}"

        return result

    @override
    def __repr__(self) -> str:
        result = f"{type(self).__name__}("
        result += f"'{hex_string(self.p)}'" if self.p > HEX_THRESHOLD else f"{self.p}"
        if self._a > HEX_THRESHOLD or self._b > HEX_THRESHOLD:
            result += f", '{hex_string(self._a)}', '{hex_string(self._b)}'"
        else:
            result += f", {self._a}, {self._b}"

        result += ")"
        return result

    def _eq_key(self) -> tuple[int, ...]:
        """Return the parameters that define the group, and nothing else.

        Curve appends its own, the way __str__ and __repr__ chain: the
        tuple is flat so that the subgroup cannot be equal to the group by
        having a shorter key compare equal.
        """
        return self.p, self._a, self._b

    @override
    def __eq__(self, other: object) -> bool:
        # a curve is its parameters: two objects built from the same ones
        # are the same curve, whatever the catalogue they came from. This
        # is not cosmetic, as the libsecp256k1 dispatch tests ec against
        # secp256k1, and the default identity comparison would silently
        # send every other object holding the secp256k1 parameters down
        # the slow Python path
        if self is other:
            return True
        # an exact type test, not isinstance alone: a CurveGroup is not a
        # Curve even when p, a and b are the same, one being every point
        # of the curve and the other a subgroup of those points, and
        # returning NotImplemented lets the reflected operand have its
        # say before Python falls back to identity
        if not isinstance(other, CurveGroup) or type(self) is not type(other):
            return NotImplemented
        return self._eq_key() == other._eq_key()

    @override
    def __hash__(self) -> int:
        # __eq__ without __hash__ would set __hash__ to None, and curves
        # are lru_cache keys in _cached_multiples below; equal curves
        # share those cache entries rather than each filling its own
        return hash(self._eq_key())

    # methods using p: they could become functions

    def negate(self, Q: Point) -> Point:
        """Return the opposite point.

        The input point is not checked to be on the curve.
        """
        # % self.p is required to account for INF (i.e. Q[1]==0)
        # so that negate(INF) = INF
        if len(Q) == 2:
            return Q[0], (self.p - Q[1]) % self.p
        raise BTClibTypeError("not a point")

    def negate_jac(self, Q: JacPoint) -> JacPoint:
        """Return the opposite Jacobian point.

        The input point is not checked to be on the curve.
        """
        # % self.p is required to account for INF (i.e. Q[1]==0)
        # so that negate(INF) = INF
        if len(Q) == 3:
            return Q[0], (self.p - Q[1]) % self.p, Q[2]
        raise BTClibTypeError("not a Jacobian point")

    def aff_from_jac_var(self, Q: JacPoint) -> Point:
        """Return the affine point: one modular inversion.

        The input point is assumed to be on the curve; infinity comes
        back as INF, its affine spelling.
        """
        if Q[2] == 0:  # Infinity point in Jacobian coordinates
            return INF

        return self._aff_from_z_inv(Q, mod_inv_var(Q[2], self.p))

    def aff_from_jac_batch_var(self, Qs: Sequence[JacPoint]) -> list[Point]:
        """Return the affine points: one modular inversion for all of them.

        `aff_from_jac_var` over a sequence, with `mod_inv_batch_var` in place of
        the one inverse each: the conversion is two products a point once
        the inverse is in hand, so a caller holding several Jacobian
        points pays one extended Euclid instead of one per point.

        The input points are assumed to be on the curve. Infinity is not
        in the batch, having no Z to invert, and comes back as INF where
        it stood.
        """
        inverses = iter(mod_inv_batch_var([Q[2] for Q in Qs if Q[2]], self.p))
        return [
            INF if Q[2] == 0 else self._aff_from_z_inv(Q, next(inverses)) for Q in Qs
        ]

    def _aff_from_z_inv(self, Q: JacPoint, z_inv: int) -> Point:
        # x is X/Z^2 and y is Y/Z^3, and both powers are built from one
        # inverse: Z^-2 is a product away from Z^-1, and Z^-3 another.
        # Inverting Z^2 and Z^3 separately is two extended Euclids where
        # this is one and two multiplications, and an inverse costs what
        # a hundred products cost -- which is also why the inverse itself
        # is the caller's, one of them being what the batch above shares
        p = self.p
        z_inv2 = z_inv * z_inv % p
        return Q[0] * z_inv2 % p, Q[1] * z_inv2 % p * z_inv % p

    def x_aff_from_jac_var(self, Q: JacPoint) -> int:
        """Return the affine x alone, without the products y costs.

        One inversion, as `aff_from_jac_var`, of Z^2 rather than of Z: the
        power x wants is the one inverted, so nothing is rebuilt from it.
        The input point is assumed to be on the curve; infinity has no
        x and is refused.
        """
        if Q[2] == 0:  # Infinity point in Jacobian coordinates
            raise BTClibValueError("INF has no x-coordinate")

        Z2 = Q[2] * Q[2]
        return (Q[0] * mod_inv_var(Z2, self.p)) % self.p

    def y_aff_from_jac_var(self, Q: JacPoint) -> int:
        """Return the affine y alone, without the product x costs.

        One inversion, as `aff_from_jac_var`, of Z^3 rather than of Z, for
        the same reason `x_aff_from_jac_var` inverts Z^2.
        The input point is assumed to be on the curve; infinity has no
        y and is refused.
        """
        if Q[2] == 0:  # Infinity point in Jacobian coordinates
            raise BTClibValueError("INF has no y-coordinate")

        Z2 = Q[2] * Q[2]
        return (Q[1] * mod_inv_var(Z2 * Q[2], self.p)) % self.p

    def is_jac_equal(self, QJ: JacPoint, PJ: JacPoint) -> bool:
        """Return True if Jacobian points are equal in affine coordinates.

        The input points are assumed to be on curve.
        """
        PJ2 = PJ[2] * PJ[2]
        QJ2 = QJ[2] * QJ[2]
        if QJ[0] * PJ2 % self.p != PJ[0] * QJ2 % self.p:
            return False

        PJ3 = PJ2 * PJ[2]
        QJ3 = QJ2 * QJ[2]
        return QJ[1] * PJ3 % self.p == PJ[1] * QJ3 % self.p

    # methods using _a, _b, p

    def add_var(self, Q1: Point, Q2: Point) -> Point:
        """Return the sum of two points.

        The input points must be on the curve.
        """
        self.require_on_curve(Q1)
        self.require_on_curve(Q2)
        # affine arithmetic, and it is not the inversion that decides it:
        # aff_from_jac_var makes one, add_aff_var makes one. The products
        # decide, and reaching this sum through Jacobian coordinates and
        # back makes more of them than add_aff_var does
        return self.add_aff_var(Q1, Q2)

    def add_jac(self, Q: JacPoint, R: JacPoint) -> JacPoint:
        """Return the sum of two Jacobian points, branch-free.

        The input points are assumed to be on the curve. One sequence
        of operations whatever the operands -- infinity and doubling
        included, the comment below saying why that is load-bearing.
        """
        # the group law has four special cases, and they are of two kinds
        # that want opposite treatment. An operand at infinity is
        # bookkeeping rather than geometry: infinity is the identity, so
        # every double-and-add starts its accumulator there and the
        # windowed ones hold it in the table as the multiple 0*Q, which
        # the digit 0 indexes. On secp256k1 that is not rare and not
        # random -- over 2000 random scalars _mult reached it 3.98 times
        # on average and only 23 of them not at all, and the count *is*
        # the secret: exactly the number of zero base-16 digits of the
        # scalar, or for _mult_jac_var the number of its low zero bits. An
        # early return there put that on the clock, 0.03 us against the
        # 3.7 us of a generic addition, and _mult measured 0.93 ms with no
        # zero digit against 0.55 ms with 63.
        #
        # So no branch on infinity, and no arithmetic on it either: a
        # Python integer costs what its size costs, and the zero
        # coordinates of infinity send half the products to zero. A
        # stand-in of full size takes its place, the table at the end
        # answers for it, and an addition with no infinity in it pays two
        # comparisons: 1.02x to 1.03x on every multiplication in the
        # package, and 1.22x on _double_mult_var, whose Shamir-Strauss loop
        # adds the infinity of a zero digit pair a quarter of the time --
        # the additions an early return answers for free, at the price of
        # putting their count on the clock. Dropping the early return
        # without the stand-ins is not enough: P + INFJ still costs
        # 1.8 us against 5.4, and _mult_jac_var is still 25% faster on a
        # scalar with 128 low zero bits
        QS = (Q, self._stand_in_q)[Q[2] == 0]
        RS = (R, self._stand_in_r)[R[2] == 0]

        p = self.p
        # every intermediate reduced as it is formed, which is what makes
        # this the fast path rather than a transcription of the formula:
        # left to grow, V3 and M*V2 reach p^9 and the products that close
        # X and Y reach p^12 -- three thousand bits on secp256k1 -- and
        # Python multiplies whatever it is handed. Worth between 2.0 and
        # 3.0 times over every mult_* variant in the package, measured
        # against the unreduced spelling on secp256k1 and secp256r1
        RZ2 = RS[2] * RS[2] % p
        RZ3 = RZ2 * RS[2] % p
        QZ2 = QS[2] * QS[2] % p
        QZ3 = QZ2 * QS[2] % p

        # the two points in a common frame: V is the difference of their
        # affine x-coordinates and W of their affine y ones, up to that
        # frame. Which is what makes the two remaining cases free to
        # detect, both being needed by the formula below -- the four
        # multiplications issue 171 counted were never their cost either,
        # M, N, T and U all feeding them too
        M = QS[0] * RZ2 % p
        T = QS[1] * RZ3 % p
        V = (RS[0] * QZ2 - M) % p
        W = (RS[1] * QZ3 - T) % p

        # the other kind, and a branch: V == 0 is one x-coordinate for
        # both points, so they are the same point -- W == 0 too, the chord
        # is the tangent, and the answer is the doubling -- or opposite
        # ones, and it is infinity. That is geometry, and inside a
        # multiplication it needs the accumulator to land on a table entry
        # or its negation: 2^-250 on a curve with a real order, against
        # the 3.98 times a random scalar reaches infinity above. What the
        # branch tells an attacker is that two points coincided, which on
        # secp256k1 they will not, and a caller spelling out P + P knows
        # it did. It is the toy curves of the test suite that take it, and
        # take it constantly, an accumulator wrapping around a group of
        # eleven points; the exhaustive test over every pair of points of
        # every one of them is what holds this branch correct. What would
        # retire the case rather than branch on it is a complete formula:
        # Renes-Costello-Batina, homogeneous coordinates, no exceptional
        # case at all -- and measured on this very fixed window 34% slower
        # for a == 0 and 59% slower for the a == p-3 of most catalogued
        # curves, on top of JacPoint being public.
        #
        # Q[2] and R[2] because V says nothing when either is zero: Z == 0
        # leaves X and Y unconstrained, and the x of INFJ is 7 while the x
        # of _jac_from_aff(INF) is 5, picked for being invalid rather than
        # for being zero, so on a curve of characteristic 7 or 5 they
        # reduce to zero and V vanishes for an operand that is not a point
        # at all -- P + INFJ answered 2*P, and eight of the ten scalar
        # multiplications this package offers were wrong for most scalars
        # on every p == 7 curve (issue 171). The stand-ins do not make it
        # safe to read: they are values, and V can be zero on a pair of
        # them too, one time in p
        if V == 0 and Q[2] and R[2]:
            return self._double_jac_helper(Q, QZ2) if W == 0 else INFJ

        V2 = V * V % p
        V3 = V2 * V % p
        MV2 = M * V2 % p

        X = (W * W - V3 - 2 * MV2) % p
        Y = (W * (MV2 - X) - T * V3) % p
        Z = V * QS[2] % p * RS[2] % p

        # and the infinity cases, answered rather than branched on. The
        # arithmetic above was done on the stand-ins and is thrown away
        # here, which is the whole point of it
        return ((X, Y, Z), R, Q, INFJ)[(Q[2] == 0) + 2 * (R[2] == 0)]

    def add_jac_aff(self, Q: JacPoint, R: Point) -> JacPoint:
        """Return the sum of a Jacobian point and an affine one, branch-free.

        `add_jac` with the second operand's Z known to be one, which is
        what an affine point is: five of the sixteen products become
        multiplications by one -- R's two powers of Z, the two that put Q
        in R's frame, and one factor of the answer's Z. libsecp256k1 keeps
        its tables in affine coordinates for exactly this and states
        `secp256k1_gej_add_ge_var` as 8 mul and 3 sqr against the 12 and 4
        of `secp256k1_gej_add_var`.

        The affine operand is a Point and not a JacPoint whose Z happens
        to be one, so the precondition is in the signature rather than in
        a sentence nothing checks.

        The input points are assumed to be on the curve. Every case
        `add_jac` answers is answered here the same way and for the same
        reasons, which its comments carry: infinity through a stand-in and
        a selection at the end, spelled `R[1] == 0` because that is what
        infinity is in affine coordinates, and the doubling and the sum
        that is infinity through the one branch on V.
        """
        QS = (Q, self._stand_in_q)[Q[2] == 0]
        RS = (R, self._stand_in_r)[R[1] == 0]

        p = self.p
        QZ2 = QS[2] * QS[2] % p
        QZ3 = QZ2 * QS[2] % p

        # M and T are Q's coordinates as they stand: R's frame is the
        # affine one, so putting Q in it is what QZ2 and QZ3 already did
        M = QS[0]
        T = QS[1]
        V = (RS[0] * QZ2 - M) % p
        W = (RS[1] * QZ3 - T) % p

        if V == 0 and Q[2] and R[1]:
            return self._double_jac_helper(Q, QZ2) if W == 0 else INFJ

        V2 = V * V % p
        V3 = V2 * V % p
        MV2 = M * V2 % p

        X = (W * W - V3 - 2 * MV2) % p
        Y = (W * (MV2 - X) - T * V3) % p
        Z = V * QS[2] % p

        return ((X, Y, Z), (R[0], R[1], 1), Q, INFJ)[(Q[2] == 0) + 2 * (R[1] == 0)]

    def double_jac(self, Q: JacPoint) -> JacPoint:
        """Return twice the Jacobian point, assumed to be on the curve."""
        # Z^2 is what the a*Z^4 term is built from and the only thing that
        # needs it, so a curve whose a is zero is handed a value the
        # helper never reads rather than a squaring and its reduction
        QZ2 = 0 if self._a_is_zero else Q[2] * Q[2] % self.p
        return self._double_jac_helper(Q, QZ2)

    def _double_jac_helper(self, Q: JacPoint, QZ2: int) -> JacPoint:
        # QZ2 is Q[2]^2 reduced mod p, which add_jac has already formed;
        # a curve whose a is zero never reads it, and double_jac above
        # does not form it. The tangent law has no case to tell apart -- a
        # point is never exceptional to itself -- so this is the whole of
        # it: no test on Q, one sequence of operations for every point of
        # the curve, and the same one for a secret point as for a public
        # one. Which is also what lets add_jac call it on every addition
        p = self.p
        QY2 = Q[1] * Q[1] % p
        # the a*Z^4 term, in the spelling this curve's a allows: the tests
        # are on the curve and not on the point, so the operations a given
        # curve makes are still the same for every point of it.
        # libsecp256k1 carries the first spelling alone, secp256k1's a
        # being zero, and states the doubling it makes as 3 mul and 4 sqr
        # against the 12 and 4 of its addition
        if self._a_is_zero:
            W = 3 * Q[0] * Q[0] % p
        elif self._a_is_minus_3:
            # 3*(X - Z^2)*(X + Z^2) is 3*X^2 - 3*Z^4, one product where
            # the general spelling below has two squarings and a product
            W = 3 * (Q[0] - QZ2) * (Q[0] + QZ2) % p
        else:
            W = (3 * Q[0] * Q[0] + self._a * QZ2 * QZ2) % p
        V = 4 * Q[0] * QY2 % p
        X = (W * W - 2 * V) % p
        Y = (W * (V - X) - 8 * QY2 * QY2) % p
        # Q[1] == 0 is both the infinity point and the two-torsion, and
        # both double to infinity, which is what Z == 0 says
        Z = 2 * Q[1] * Q[2] % p
        return X, Y, Z

    def add_aff_var(self, Q: Point, R: Point) -> Point:
        """Return the sum of two affine points, assumed on the curve.

        One modular inversion; the special cases are branched on, the
        comment below saying why affine coordinates leave no choice.
        """
        # infinity is a special case here and cannot stop being one: an
        # affine point is two field elements and the group has one point
        # more than any pair of them can name, so INF is spelled y == 0
        # (alias.py) and no formula reaches it. That spelling is also why
        # a two-torsion point, the one real point with y == 0, has no
        # affine form at all -- Jacobian coordinates do hold it, Z != 0
        # telling it from infinity, and add_jac doubles it to infinity
        # correctly; none of the low-cardinality test curves has one.
        # The order is load-bearing too, and it is this one rather than
        # the doubling test first: INF is (5, 0), its x-coordinate
        # arbitrary, so a doubling test reading it ahead of here answers
        # "same x, different y, hence INF" for INF + P whenever P has
        # x == 5 -- and ec23_19 of the test suite is generated by (5, 4),
        # which is exactly that point (issue 171)
        if R[1] == 0:  # Infinity point in affine coordinates
            return Q
        if Q[1] == 0:  # Infinity point in affine coordinates
            return R

        # then doubling: two equal points make the chord a tangent and the
        # slope below 0/0. Branches, where add_jac computes every case and
        # selects, because there is nothing here for that to protect: the
        # mod_inv_var this path exists to spend is an extended Euclid, whose
        # iteration count follows the value it is inverting, so the affine
        # law cannot be made uniform whatever is done to these three tests
        if R[0] == Q[0]:
            return self.double_aff_var(R) if R[1] == Q[1] else INF

        p = self.p
        # lam reduced before it is squared, as in add_jac, though here it
        # is worth 6% of _mult_aff_var rather than a factor of two:
        # mod_inv_var is what affine coordinates cost, and is why the
        # ladders are not
        lam = (R[1] - Q[1]) * mod_inv_var(R[0] - Q[0], p) % p
        x = (lam * lam - Q[0] - R[0]) % p
        y = (lam * (Q[0] - x) - Q[1]) % p
        return x, y

    def double_aff_var(self, Q: Point) -> Point:
        """Return twice the affine point, assumed to be on the curve."""
        if Q[1] == 0:  # Infinity point in affine coordinates
            return INF

        p = self.p
        lam = (3 * Q[0] * Q[0] + self._a) * mod_inv_var(2 * Q[1], p) % p
        x = (lam * lam - Q[0] - Q[0]) % p
        y = (lam * (Q[0] - x) - Q[1]) % p
        return x, y

    def _y2(self, x: int) -> int:
        # skipping a crucial check here:
        # if sqrt(y*y) does not exist, then x is not valid.
        # This is a good reason to keep this method private
        return ((x**2 + self._a) * x + self._b) % self.p

    def y_var(self, x: int) -> int:
        """Return the y coordinate from x, as in (x, y)."""
        if not 0 <= x < self.p:
            err_msg = "x-coordinate not in 0..p-1: "
            err_msg += f"{hex_string(x)}" if x > HEX_THRESHOLD else f"{x}"
            raise BTClibValueError(err_msg)
        y2 = self._y2(x)
        try:
            return mod_sqrt_var(y2, self.p)
        except BTClibValueError as e:
            err_msg = "invalid x-coordinate: "
            err_msg += f"{hex_string(x)}" if x > HEX_THRESHOLD else f"{x}"
            raise BTClibValueError(err_msg) from e

    def require_on_curve(self, Q: Point) -> None:
        """Require the input curve Point to be on the curve.

        An Error is raised if not.
        """
        if not self.is_on_curve(Q):
            raise BTClibValueError("point not on curve")

    def is_on_curve(self, Q: Point) -> bool:
        """Return True if the point is on the curve."""
        # the type before the length: `len` of what is not sized is a
        # TypeError about a builtin, where a Point is what this asks for
        assert_type(Q, tuple, "point")
        if len(Q) != 2:
            raise BTClibValueError("point must be a tuple[int, int]")
        # the type before the y==0 infinity check below: `False == 0`
        # would read any x paired with a bool y as infinity, and
        # `is_integer` is where this library says a bool is not a number
        # (issue #1249)
        if not is_integer(Q[0]):
            raise BTClibTypeError(f"non-integer x-coordinate: {Q[0]}")
        if not is_integer(Q[1]):
            raise BTClibTypeError(f"non-integer y-coordinate: {Q[1]}")
        if Q[1] == 0:  # Infinity point in affine coordinates
            return True
        if not 0 < Q[1] < self.p:  # y cannot be zero
            raise BTClibValueError(f"y-coordinate not in 1..p-1: '{hex_string(Q[1])}'")
        return self._y2(Q[0]) == (Q[1] * Q[1] % self.p)

    #  y-symmetry tiebreaker criteria: even/odd, low/high, or quadratic residue

    def y_even_var(self, x: int) -> int:
        """Return the odd/even affine y-coordinate associated to x."""
        root = self.y_var(x)
        # switch even/odd root as needed (XORing the conditions)
        return self.p - root if root % 2 else root

    def y_low_var(self, x: int) -> int:
        """Return the low/high affine y-coordinate associated to x."""
        root = self.y_var(x)
        return root if root <= self.p // 2 else self.p - root

    def y_quadratic_residue_var(self, x: int) -> int:
        """Return the quadratic residue affine y-coordinate."""
        if not self.p_is_3_mod_4:
            err_msg = "field prime is not equal to 3 mod 4: "
            err_msg += (
                f"'{hex_string(self.p)}'" if self.p > HEX_THRESHOLD else f"{self.p}"
            )
            raise BTClibValueError(err_msg)
        # for a p of this form self.y answers the residue root already:
        # it is a ** ((p + 1) // 4), a power of the square a and so a
        # square itself, which leaves p - root the non-residue, -1 being
        # one modulo such a p. Asking legendre_symbol_var which of the two
        # this is would spend a second exponentiation the size of the
        # first to be told what the exponent settles
        return self.y_var(x)


