def _mult_recursive_aff_var(m: int, Q: Point, ec: CurveGroup) -> Point:
    """Scalar multiplication of a curve point in affine coordinates.

    This implementation uses a recursive version of 'double & add',
    affine coordinates.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    if m == 0:
        return INF

    if m % 2 == 1:
        return ec.add_aff_var(Q, _mult_recursive_aff_var((m - 1), Q, ec))

    return _mult_recursive_aff_var((m // 2), ec.double_aff_var(Q), ec)


def _mult_recursive_jac_var(m: int, Q: JacPoint, ec: CurveGroup) -> JacPoint:
    """Scalar multiplication of a curve point in affine coordinates.

    This implementation uses a recursive version of 'double & add',
    jacobian coordinates.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    if m == 0:
        return INFJ

    if m % 2 == 1:
        return ec.add_jac(Q, _mult_recursive_jac_var((m - 1), Q, ec))

    return _mult_recursive_jac_var((m // 2), ec.double_jac(Q), ec)


def _mult_aff_var(m: int, Q: Point, ec: CurveGroup) -> Point:
    """Scalar multiplication of a curve point in affine coordinates.

    This implementation uses 'double & add' algorithm, 'right-to-left'
    binary decomposition of the m coefficient, affine coordinates.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # R[0] is the running result, R[1] = R[0] + Q is an ancillary variable
    R = [INF, Q]
    # if least significant bit of m is 1, then add Q to R[0]
    R[0] = R[m & 1]
    # remove the bit just accounted for
    m >>= 1
    while m > 0:
        # the doubling part of 'double & add'
        Q = ec.double_aff_var(Q)
        # always perform the 'add', even if useless: one addition per bit
        # whatever the bit is, as in _mult_jac_var. It buys less here,
        # add_aff_var branching on its own cases and mod_inv_var taking the time
        # its input asks for, which is why the affine variants are the
        # readable ones rather than the ones to sign with
        R[1] = ec.add_aff_var(R[0], Q)
        # if least significant bit of m is 1, then add Q to R[0]
        R[0] = R[m & 1]
        m >>= 1
    return R[0]


def _mult_jac_var(m: int, Q: JacPoint, ec: CurveGroup) -> JacPoint:
    """Scalar multiplication of a curve point in Jacobian coordinates.

    This implementation uses 'double & add' algorithm, 'right-to-left'
    binary decomposition of the m coefficient, Jacobian coordinates.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # R[0] is the running result, R[1] = R[0] + Q is an ancillary variable
    R = [INFJ, Q]
    # if least significant bit of m is 1, then add Q to R[0]
    R[not m & 1] = Q
    # remove the bit just accounted for
    m >>= 1
    while m > 0:
        # the doubling part of 'double & add'
        Q = ec.double_jac(Q)
        # always perform the addition, even if useless, but use it as R[0]
        # only if the least significant bit of m is 1: one doubling and
        # one addition per bit, and with a branch-free add_jac under it
        # the loop costs the same for every scalar of a given length
        R[not m & 1] = ec.add_jac(R[0], Q)
        m >>= 1
    return R[0]


def _multiples(Q: JacPoint, size: int, ec: CurveGroup) -> list[JacPoint]:
    """Return {k_i * Q} for k_i in {0, ..., size-1}."""
    if size < 2:
        raise BTClibValueError(f"size too low: {size}")

    k, odd = divmod(size, 2)
    T = [INFJ, Q]
    for i in range(3, k * 2, 2):
        # not T.extend((double_jac(...), add_jac(T[-1], Q))): a tuple
        # literal evaluates both elements before either is appended, so
        # T[-1] there would still be the previous iteration's, not the
        # double_jac just computed -- preview's FURB113 suggests it and
        # unsafe-fixes applies it without noticing
        T.append(ec.double_jac(T[(i - 1) // 2]))
        T.append(ec.add_jac(T[-1], Q))

    if odd:
        T.append(ec.double_jac(T[(size - 1) // 2]))

    return T


MAX_W = 5


@functools.lru_cache  # results are cached to increase efficiency
def _cached_multiples(Q: JacPoint, ec: CurveGroup) -> list[JacPoint]:
    """Return the multiples 0..(2^MAX_W - 1) of Q, memoized on (Q, ec).

    The table the fixed-window ladder indexes when asked to cache; the
    memoization pays because the generator is the Q of most calls.
    """
    T = [INFJ, Q]
    for i in range(3, 2**MAX_W, 2):
        # not extend(): _multiples() above has why
        T.append(ec.double_jac(T[(i - 1) // 2]))
        T.append(ec.add_jac(T[-1], Q))
    return T


@functools.lru_cache  # results are cached to increase efficiency
def _cached_multiples_fixwind(
    Q: JacPoint, ec: CurveGroup, w: int
) -> list[list[JacPoint]]:
    """Made to precompute values for _mult_fixed_window_cached_var.

    Do not use it for other functions. Made to be used for w=4, do not
    use w.
    """
    T = []
    K = Q
    for _ in range((ec.p_size * 8) // w + 1):
        sublist = [INFJ, K]
        for j in range(3, 2**w, 2):
            # not extend(): _multiples() above has why
            sublist.append(ec.double_jac(sublist[(j - 1) // 2]))
            sublist.append(ec.add_jac(sublist[-1], K))
        K = ec.double_jac(sublist[2 ** (w - 1)])
        T.append(sublist)

    return T


def _convert_number_to_base(i: int, base: int) -> list[int]:
    """Return the digits of an integer in the requested base."""
    digits: list[int] = []
    while i or not digits:
        i, idx = divmod(i, base)
        digits.append(idx)
    return digits[::-1]


def _mods(m: int, w: int) -> int:
    """Signed modulo function."""
    w2: int = pow(2, w)
    M = m % w2
    return M - w2 if (w2 // 2) <= M else M


def _wNAF_of_m(m: int, w: int) -> list[int]:
    """WNAF (width-w Non-adjacent form) of number m.

    Given an integer m, wNAF is a method of representation
    with powers of 2, where the coefficients are odd or 0,
    and where at most one of any w consecutive digits is nonzero.
    It has the following properties:
    - m has a unique width-w NAF.
    -The length of wNAF(m) is at most one more than the length of the binary
    representation of k.
    -The average density of nonzero digits is approximately 1/(w + 1).

    This recoding sits here next to _convert_number_to_base, the same kind
    of integer-only helper, rather than with the wNAF multiplications of
    curve_group_2: the interleaved _multi_mult_w_NAF_var below needs it, and
    curve_group cannot import the module that imports it.

    For complete reference see:
    D. Hankerson, 'Guide to Elliptic Curve Cryptography' chapter 3
    """
    i = 0

    M: list[int] = []
    while m > 0:
        if (m % 2) == 1:
            if w == 1:
                # Computing binary NAF of m
                M.append(2 - (m % 4))
            else:
                # Computing wNAF of m
                M.append(_mods(m, w))
            m -= M[i]
        else:
            M.append(0)
        m //= 2
        i += 1

    return M


def signed_odd_digits(m: int, w: int, size: int) -> list[int]:
    """Return the size signed odd base-2^w digits of an odd m.

    Regular recoding, Joye-Tunstall: m = sum(digits[i] * 2^(w*i)) with
    every digit odd and in {±1, ±3, ..., ±(2^w - 1)}, least significant
    first, as _wNAF_of_m returns its own. Two properties are what it is
    for, and neither is the wNAF's:

    - no digit is zero, so the multiplication that indexes them makes one
      addition per digit whatever m is, where a wNAF adds on a nonzero
      digit and so once per unit of the recoded weight
    - the count is `size` and not the length of m, so a scalar's *size*
      stops being visible too

    The digits are signed, and that is what buys the first property: 2^w
    odd values in -(2^w - 1)..2^w - 1 name 2^(w-1) points and their
    opposites, and negating a Jacobian point is one modular subtraction.

    m must be odd -- a sum of odd digits weighted by powers of 2 has the
    parity of digits[0], so no even number has such a form at all -- and
    must fit the size asked for, which is `m < 2^(w*size)`: the last digit
    is what is left of m and is not reduced further.
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")
    # a number cannot be written in basis 1 (ie w=0)
    if w <= 0:
        raise BTClibValueError(f"non positive w: {w}")
    if m % 2 == 0:
        raise BTClibValueError(f"even m: {hex(m)}")
    if size < 1:
        raise BTClibValueError(f"size too low: {size}")
    if m >> (w * size):
        raise BTClibValueError(f"m does not fit {size} digits: {hex(m)}")

    w2 = 1 << w
    digits: list[int] = []
    for _ in range(size - 1):
        # the low w+1 bits of m read as a signed value: odd, since m is,
        # and in -(2^w - 1)..2^w - 1
        digit = (m % (2 * w2)) - w2
        digits.append(digit)
        # m - digit is 2^w times an odd number -- m - (m mod 2^(w+1)) is a
        # multiple of 2^(w+1) and 2^w is added back to it -- so the next
        # digit is odd in its turn, and the recoding never needs a zero
        m = (m - digit) >> w
    # what is left, which the bound above makes an odd digit of its own:
    # positive, so the accumulator can start at the entry it names
    digits.append(m)
    return digits


def _odd_multiples(Q: JacPoint, ec: CurveGroup, w: int) -> list[JacPoint]:
    """Return the odd multiples 1*Q, 3*Q, ..., (2^(w-1) - 1)*Q.

    The table a width-w NAF indexes: its digits are odd and smaller than
    2^(w-1) in absolute value, so a digit d picks entry (abs(d) - 1) // 2,
    to be negated on the fly when d is negative. For w of 1 or 2 the
    digits are only +-1 and the table is the point itself.
    """
    T = [Q]
    if w > 2:
        Q2 = ec.double_jac(Q)
        for _ in range(2 ** (w - 2) - 1):
            T.append(ec.add_jac(T[-1], Q2))
    return T


def _odd_multiples_aff(Q: JacPoint, ec: CurveGroup, w: int) -> list[Point]:
    """Return `_odd_multiples` in affine coordinates, one inversion for all.

    What it buys is the loop that indexes it: `add_jac_aff` makes five
    products fewer than `add_jac` on every addition, and a windowed
    multiplication makes one addition per window. What it costs is one
    extended Euclid, `aff_from_jac_batch_var` sharing it across the entries --
    at w=4 one inverse and some forty products, against five saved on each
    of the ~63 additions a 256-bit scalar makes.

    The inversion is a function of the point and not of the scalar, so a
    multiplication that is regular in its scalar stays regular in it.
    """
    return ec.aff_from_jac_batch_var(_odd_multiples(Q, ec, w))


# the width a point of ec._fixed_points has its table built at, against
# the narrow one a point that arrives once is worth. The measurement is in
# _multi_mult_w_NAF_var's docstring
_FIXED_POINT_W = 10


@functools.lru_cache  # a fixed point's table is the same on every call
def _cached_odd_multiples_aff(Q: JacPoint, ec: CurveGroup, w: int) -> list[Point]:
    """Return `_odd_multiples_aff` memoized, for a point known in advance.

    What memoizing buys is not the building alone: a table that is not
    rebuilt can be held at a width a per-call one could not pay for, and a
    wNAF has one nonzero digit in w+1, so the wider window is fewer
    additions in the loop that indexes it. libsecp256k1 splits the two the
    same way, `WINDOW_A` of 5 for the variable point against a `WINDOW_G`
    of 15 for the generator, whose table it generates at build time.

    Only a point somebody has said will come back may be handed here:
    `ec._fixed_points`, or one a caller prepared with
    `curve.PreparedPoint`. A table memoized on whatever key arrives is a
    table built once, used once and kept for ever, which is why the
    preparing is a caller's word and never inferred -- issue #287 is the
    same bound `_cached_base58_decode` and `pedersen.second_generator`
    hold. What bounds it when the word is given is this cache's own
    maxsize, 128 tables of 2^(w-2) points.
    """
    return _odd_multiples_aff(Q, ec, w)


def _signed_odd_multiples_aff(Q: JacPoint, ec: CurveGroup, w: int) -> list[Point]:
    """Return the 2^w multiples a signed odd width-w digit names, affine.

    -(2^w - 1)*Q first and (2^w - 1)*Q last, so the digit d of
    `signed_odd_digits` picks entry (d + 2^w - 1) // 2 and nothing has to
    test its sign, where the wNAF loops negate an entry of
    `_odd_multiples_aff` on the fly under an `if`. Cheaper, too, and not
    only regular: 2^(w-1) modular subtractions once -- 8 of them at w=4 --
    against the one per negative digit the loop would make, which is half
    of the 64 digits a 256-bit scalar has at that width.

    The table it is built on is `_odd_multiples_aff(Q, ec, w + 1)`: a
    regular digit reaches 2^w - 1 where a width-w NAF digit stops at
    2^(w-1) - 1, so the table is twice as long as that recoding's for the
    same window. The negation is one modular subtraction in affine
    coordinates as it is in Jacobian ones, `(x, p - y)`, so nothing is
    paid for the entries being affine here rather than there.
    """
    T = _odd_multiples_aff(Q, ec, w + 1)
    return [ec.negate(P) for P in reversed(T)] + T


@functools.lru_cache  # the generator is the Q of most calls, so it pays
def _cached_fixed_base_multiples(
    Q: JacPoint, ec: CurveGroup, w: int
) -> list[list[Point]]:
    """Return one signed odd affine table per digit position of a scalar.

    Entry i is `_signed_odd_multiples_aff(2^(w*i) * Q, ec, w)`, so a
    scalar's i-th width-w digit indexes the multiple it names outright and
    a multiplication built on this makes no doubling at all. The positions
    are `ceil(ec.scalar_len / w)`, which is every digit a scalar of the
    group has; a larger scalar has no table and `signed_odd_digits`
    refuses it.

    Memoized on (Q, ec, w) because that is what makes it worth building:
    the table is the point's and not the scalar's, so a caller
    multiplying the generator pays for it once -- and so does a caller
    multiplying its own point, once it has said with
    `curve.PreparedPoint` that the point will come back. What it costs
    to keep is
    2^w points a position -- on secp256k1 at the w=6 `curve.py` passes,
    43 positions of 64 points, some 366 KiB and 9.3 ms to build, which is
    the trade `_mult_fixed_base` measures.
    """
    tables: list[list[Point]] = []
    K = Q
    for _ in range(ceil(ec.scalar_len / w)):
        tables.append(_signed_odd_multiples_aff(K, ec, w))
        for _ in range(w):
            K = ec.double_jac(K)
    return tables


def _mult_fixed_base(m: int, Q: JacPoint, ec: CurveGroup, w: int) -> JacPoint:
    """Scalar multiplication with a table per digit position: no doublings.

    `_mult_regular_window` with the doublings taken out of it as well as
    the zero digits: that one holds one table and doubles w times between
    digits, this one holds a table per position and only adds. So a
    256-bit scalar costs `ceil(ec.scalar_len / w)` additions and nothing
    else -- 43 of them at w=6, against 71 additions and 253 doublings --
    and the count is the same for every scalar of the curve, which is
    what the regular window is for and what this keeps.

    w=6 by measurement, over 30 random 256-bit scalars on secp256k1, best
    of seven alternating rounds. The window buys time and is paid in
    memory, and the time does not turn: 193 us at w=4, 157 at w=5, 127 at
    w=6, 110 at w=7, 96 at w=8, against tables of 136, 221, 366, 629 and
    1088 KiB. Where to stop is therefore where the memory stops being
    worth it, and past w=6 a doubled table buys under 15% each time.

    Against what `curve.mult` ran before, at w=6: 2.77x, 3.42x and 4.13x
    at w=4, 5 and 6 over the GLV endomorphism's 537 us on secp256k1, and
    5.98x over the regular window's 785 us on secp256r1, which has no
    endomorphism to be measured against and gains the more for it. The
    two curves hold tables of the same size.

    It is libsecp256k1's `secp256k1_ecmult_gen`, which sums one
    precomputed entry per digit position and doubles nothing, and it
    applies for the same reason: the point is the curve's generator, the
    same on every call, so its table is built once and kept.
    `curves.mult` is what recognizes that case.

    The reason is the point repeating and not the point being the
    generator, so `curve.PreparedPoint` reaches here as well, for a
    caller who has said its own point will come back. Break-even is 23
    multiplications of that point: 9.50 ms and 366 KiB to build against
    142.3 us a call warm, where the GLV endomorphism `curves.mult`
    otherwise runs costs 551.0 with nothing to build. Which is why
    nothing infers it -- the same measurement, read the other way, is
    9.5 ms and 366 KiB of pure loss for a point multiplied once.

    The accumulator is rescaled where `curves.mult` rescales the point on
    its other arm: the table here is memoized and canonical, so it is the
    running value that has to stop being a function of m alone.
    `_blinded_jac` says what that buys and what it does not.

    The input point is assumed to be on the curve, and m to be below
    2^(w * positions) -- which `ec.scalar_len` bounds and every entry
    point of the library satisfies, each reducing mod n first.
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # a number cannot be written in basis 1 (ie w=0)
    if w <= 0:
        raise BTClibValueError(f"non positive w: {w}")

    T = _cached_fixed_base_multiples(Q, ec, w)
    digits = signed_odd_digits(m | 1, w, len(T))
    offset = (1 << w) - 1

    # a table entry, the top digit being positive, and never infinity
    R = _blinded_jac(_jac_from_aff(T[-1][(digits[-1] + offset) // 2]), ec)
    for i in range(len(T) - 2, -1, -1):
        # only 'add': the position's own table holds the power of two
        R = ec.add_jac_aff(R, T[i][(digits[i] + offset) // 2])
    # the parity correction of _mult_regular_window, made whatever the
    # parity for the same reason, and what answers m == 0
    return ec.add_jac(R, (INFJ, ec.negate_jac(Q))[not m & 1])


def _mult_mont_ladder_var(m: int, Q: JacPoint, ec: CurveGroup) -> JacPoint:
    """Scalar multiplication using 'Montgomery ladder' algorithm.

    This implementation uses
    'Montgomery ladder' algorithm,
    'left-to-right' binary decomposition of the m coefficient,
    Jacobian coordinates.

    The loop body is one addition and one doubling for every bit of m,
    and the bit only picks which of the two accumulators each is applied
    to: no test on the scalar, which is what the FLUSH+RELOAD recovery of
    OpenSSL's nonces read out of a double-and-add. With add_jac branching
    on nothing either, this is the variant of the package that comes
    closest to constant-time, and what is left is the loop itself: it
    runs once per bit of m, so the length of a scalar is not hidden, only
    its bits. See:
    - https://eprint.iacr.org/2014/140

    The input point is assumed to be on curve and
    the m coefficient is assumed to have been reduced mod n
    if appropriate (e.g. cyclic groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # R[0] is the running resultR[1] = R[0] + Q is an ancillary variable
    R = [INFJ, Q]
    for i in [int(i) for i in f"{m:b}"]:
        R[not i] = ec.add_jac(R[i], R[not i])
        R[i] = ec.double_jac(R[i])
    return R[0]


def _mult_base_3_var(m: int, Q: JacPoint, ec: CurveGroup) -> JacPoint:
    """Scalar multiplication using ternary decomposition of the scalar.

    This implementation uses 'triple & add' algorithm, 'left-to-right'
    ternary decomposition of the m coefficient, Jacobian coordinates.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # at each step one of the points in T will be added
    T = [INFJ, Q, ec.double_jac(Q)]

    digits = _convert_number_to_base(m, 3)

    R = T[digits[0]]
    for i in digits[1:]:
        # 'triple'
        R2 = ec.double_jac(R)
        R3 = ec.add_jac(R2, R)
        # and 'add'
        R = ec.add_jac(R3, T[i])
    return R


def _mult_fixed_window_var(
    m: int, Q: JacPoint, ec: CurveGroup, w: int, cached: bool
) -> JacPoint:
    """Scalar multiplication using "fixed window".

    This implementation uses 'multiple-double & add' algorithm, 'left-
    to-right' window decomposition of the m coefficient, Jacobian
    coordinates.

    For 256-bit scalars it is suggested to choose w=4 or w=5.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # a number cannot be written in basis 1 (ie w=0)
    if w <= 0:
        raise BTClibValueError(f"non positive w: {w}")

    # at each step one of the points in T will be added
    T = _cached_multiples(Q, ec) if cached else _multiples(Q, 2**w, ec)

    digits = _convert_number_to_base(m, 2**w)

    R = T[digits[0]]
    for i in digits[1:]:
        # multiple 'double'
        for _ in range(w):
            R = ec.double_jac(R)
        # and 'add'
        R = ec.add_jac(R, T[i])
    return R


def _mult_fixed_window_cached_var(
    m: int, Q: JacPoint, ec: CurveGroup, w: int
) -> JacPoint:
    """Scalar multiplication using "fixed window" & cached values.

    This implementation uses 'multiple-double & add' algorithm, 'left-
    to-right' window decomposition of the m coefficient, Jacobian
    coordinates.

    For 256-bit scalars it is suggested to choose w=4. Thanks to the
    pre-computed values, it just needs addictions.

    The input point is assumed to be on curve and the m coefficient is
    assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # a number cannot be written in basis 1 (ie w=0)
    if w <= 0:
        raise BTClibValueError(f"non positive w: {w}")

    T = _cached_multiples_fixwind(Q, ec, w)

    digits = _convert_number_to_base(m, 2**w)

    k = len(digits) - 1

    R = T[k][digits[0]]

    for i in range(1, len(digits)):
        k -= 1
        # only 'add'
        R = ec.add_jac(R, T[k][digits[i]])
    return R


def _mult_regular_window(m: int, Q: JacPoint, ec: CurveGroup, w: int) -> JacPoint:
    """Scalar multiplication using a regular window: no digit is zero.

    The fixed window above, with the quantity the scalar still decided
    taken away from it (issue 254). That one adds a table entry on every
    digit, the infinity of T[0] included, so *which* digits a scalar has
    does not change what it costs -- but how many it has does: the count
    is ceil(m.bit_length() / w), and a scalar short of a full top window
    runs one window less. Here the digits are the signed odd ones of
    signed_odd_digits, none of them zero, and there are
    ceil(ec.scalar_len / w) of them whatever m is: one addition and w
    doublings per window, for every scalar of every size. Measured on
    secp256k1 over 200 random scalars: 68 to 70 additions and 251 to 259
    doublings for the fixed window, and 71 and 253 for this one on every
    one of them.

    Uniformity for free, in other words -- 0.815 ms against 0.812 over 30
    random 256-bit scalars, best of five -- which is what makes this the
    `_mult` the package reaches for rather than an option beside it. The
    fixed window stays as what it is didactically, the plain one, and the
    wNAF multiplications stay the fast irregular ones for coefficients
    that are public: `_double_mult_w_NAF_var` is what verification runs.

    w=4 by measurement, as for the fixed window: 0.803 ms at w=5 and 0.831
    at w=6, the window paying for a table twice the size of the NAF's at
    the same width.

    Two things follow for the group law underneath. The accumulator starts
    at a table entry instead of at infinity and no digit names infinity, so
    the identity is unreachable from the loop rather than merely uniform in
    it; and the two special cases left in `add_jac`, a doubling and a sum
    that is infinity, need the accumulator to land on a table entry or its
    opposite, 2^-250 on a curve with a real order. On the toy curves of
    the test suite they are reached constantly, an accumulator wrapping
    around a group of eleven points, which is what holds them tested.

    The input point is assumed to be on curve. m is *not* assumed to have
    been reduced: a scalar above ec.scalar_len bits is multiplied in the
    digits it needs, which is the one case where the count is the scalar's
    own again -- and no entry point of the library forms one, each reducing
    mod n first.
    """
    if m < 0:
        raise BTClibValueError(f"negative m: {hex(m)}")

    # a number cannot be written in basis 1 (ie w=0)
    if w <= 0:
        raise BTClibValueError(f"non positive w: {w}")

    size = ceil(max(ec.scalar_len, m.bit_length()) / w)
    # the recoding needs an odd scalar, and m | 1 is m for an odd one and
    # m + 1 for an even one. The final addition below takes the 1 back
    # rather than n being added to make m odd: n is not on CurveGroup at
    # all, and m + n would be the same point only for a point whose order
    # it is -- which the group this multiplies in cannot say
    digits = signed_odd_digits(m | 1, w, size)
    T = _signed_odd_multiples_aff(Q, ec, w)
    offset = (1 << w) - 1

    # a table entry, the top digit being positive, and never infinity
    R = _jac_from_aff(T[(digits[-1] + offset) // 2])
    for digit in digits[-2::-1]:
        # multiple 'double'
        for _ in range(w):
            R = ec.double_jac(R)
        # and 'add', on every digit: there is no zero one to skip
        R = ec.add_jac_aff(R, T[(digit + offset) // 2])
    # the parity correction, made whatever the parity so that it cannot be
    # read off the clock: one addition of infinity, which by the same
    # property costs what the addition of -Q costs. It is also what
    # answers m == 0, whose recoding is that of 1
    return ec.add_jac(R, (INFJ, ec.negate_jac(Q))[not m & 1])


# the width _mult hands the regular window; the measurement behind it is
# in the docstring of the function it is passed to
_MULT_W = 4


def _mult(m: int, Q: JacPoint, ec: CurveGroup) -> JacPoint:
    """Return m*Q, with what the rest of the package multiplies with.

    On every curve but secp256k1, where curves.mult has the GLV
    endomorphism: the regular window, whose cost is the same for every
    scalar of the curve, at the cost of nothing measurable against the
    fixed window it recodes.

    A function and not an alias of _mult_regular_window, the width being an
    argument: a private signature carries no default, so the width this one
    picks belongs here, where the choice is, rather than in the signature of
    a variant every other caller passes its own width to.
    """
    return _mult_regular_window(m, Q, ec, _MULT_W)


def _double_mult_var(
    u: int, HJ: JacPoint, v: int, QJ: JacPoint, ec: CurveGroup
) -> JacPoint:
    """Double scalar multiplication (u*H + v*Q).

    This implementation uses the Shamir-Strauss algorithm, 'left-to-
    right' binary decomposition of the u and v coefficients, Jacobian
    coordinates.

    Strauss algorithm consists of a single 'double & add' loop for the
    parallel calculation of u*H and v*Q, efficiently using a single
    'doubling' for both scalar multiplications (see

    https://stackoverflow.com/questions/50993471/ec-scalar-multiplication-with-strauss-shamir-method).
    The Shamir trick adds the precomputation of H+Q,
    which is to be added in the loop when the binary digits
    of u and v are both equal to 1 (on average 1/4 of the cases).

    The input points are assumed to be on curve,
    the u and v coefficients are assumed to have been reduced mod n
    if appropriate (e.g. cyclic groups of order n).
    """
    if u < 0:
        raise BTClibValueError(f"negative first coefficient: {hex(u)}")
    if v < 0:
        raise BTClibValueError(f"negative second coefficient: {hex(v)}")

    # at each step one of the following points will be added
    T = [INFJ, HJ, QJ, ec.add_jac(HJ, QJ)]
    # which one depends on binary digit for that step
    ui = f"{u:b}"
    vi = f"{v:b}".zfill(len(ui))
    ui = ui.zfill(len(vi))
    digits = [int(j) + 2 * int(k) for j, k in zip(ui, vi, strict=True)]
    # R[0] is the running result, R[1] = R[0] + T[*] is an ancillary variable
    R = T[digits[0]]
    for i in digits[1:]:
        # the doubling part of 'double & add'
        R = ec.double_jac(R)
        # always perform the 'add', even if the digit pair is 0 and the
        # entry it names is infinity: one addition per step, whatever the
        # coefficients. Which is where an add_jac that does not shortcut
        # infinity is dearest -- a quarter of the pairs are 0 on average,
        # each an addition a shortcut would answer for free -- and it is
        # the one place in the package that measures 22% slower for it,
        # against the 2% to 3% everywhere else
        R = ec.add_jac(R, T[i])
    return R


def _multi_mult_pairs(
    scalars: Sequence[int], jac_points: Sequence[JacPoint]
) -> list[tuple[int, JacPoint]]:
    """Check the arguments of a multi multiplication and drop the zeros.

    Shared by the two implementations below so that they answer the same
    errors to the same arguments: whichever of them _multi_mult_var calls is
    a performance decision, and a caller must not be able to tell which
    it got. A zero scalar contributes nothing to the sum and is dropped
    rather than carried, which Bos-Coster needs -- it would be a zero
    divisor in its Euclidean step -- and interleaved wNAF is glad of,
    a scalar of zero costing a table it would never index.
    """
    if len(scalars) != len(jac_points):
        err_msg = "mismatch between number of scalars and points: "
        err_msg += f"{len(scalars)} vs {len(jac_points)}"
        raise BTClibValueError(err_msg)

    if len(scalars) < 2:
        raise BTClibValueError("not a multi_mult_var")

    pairs: list[tuple[int, JacPoint]] = []
    for n, PJ in zip(scalars, jac_points, strict=True):
        if n < 0:
            raise BTClibValueError(f"negative coefficient: {hex(n)}")
        if n:
            pairs.append((n, PJ))
    return pairs


# the width _multi_mult_var hands the interleaved wNAF; the measurement
# behind it is in the docstring of the function it is passed to
_MULTI_MULT_W = 5


def _additions_by_position(
    nafs: Sequence[list[int]], tables: Sequence[list[Point]], ec: CurveGroup
) -> list[list[Point]]:
    """Return the points each bit position adds, indexed by position.

    An entry per position, holding the table entry every wNAF with a nonzero
    digit there names -- negated where the digit is, a signed digit naming a
    point and its opposite. What it replaces is every wNAF being asked for a
    digit at every position: a wNAF has one nonzero digit in w+1, so a
    secp256k1 double multiplication asked 512 questions -- 128 positions
    over the four halves the GLV split makes -- and answered 79 of them with
    an addition. The 433 that answered nothing were a `zip` step, a
    comparison against a `len` recomputed per iteration, and an index that
    found a zero (issue 906).

    Read this way round the digits are walked once, where each one was read
    at the position it belongs to and skipped at every other, and the loop
    that consumes the answer is a doubling and its additions. The table
    index and the negation are here rather than there for the same reason:
    they are what a digit means, and the loop has no use for the digit
    itself.

    The doublings and the additions are the same operations in the same
    order, this being where a digit is looked up and not what is done with
    it -- `test_the_interleaved_loop_makes_the_operations_its_wnafs_name`
    asserts the sequence of both, with the point each addition takes,
    against the sequence the wNAFs name. A comparison of results would be
    blind to a reordering that answers the same point, group addition
    commuting.

    The gain is CPython's: the loop control this removes is what a tracing
    JIT flattens on its own, and under PyPy the two spellings measure the
    same. CHANGELOG.md has the figures, this being a docstring and they
    being about code that is no longer here.
    """
    at_position: list[list[Point]] = [[] for _ in range(max(len(naf) for naf in nafs))]
    for naf, T in zip(nafs, tables, strict=True):
        for j, d in enumerate(naf):
            if d:
                at_position[j].append(
                    T[(d - 1) // 2] if d > 0 else ec.negate(T[(-d - 1) // 2])
                )
    return at_position


def _multi_mult_w_NAF_var(
    scalars: Sequence[int],
    jac_points: Sequence[JacPoint],
    ec: CurveGroup,
    w: int,
    fixed: frozenset[JacPoint],
) -> JacPoint:
    """Return the multi scalar multiplication u1*Q1 + ... + un*Qn.

    Strauss' algorithm with interleaved wNAFs, the many-point form of
    curve_group_2's _double_mult_w_NAF_var (HMV algorithm 3.51): each scalar
    gets its own width-w NAF and its own table of odd multiples, and a
    single left-to-right loop shares one doubling per bit position among
    all of them, adding a (possibly negated) table entry wherever a NAF
    has a nonzero digit.

    Sharing the doublings is the whole of the idea, and what the dispatch
    of _multi_mult_var weighs: the ~256 doublings a 256-bit scalar needs are
    paid once for the batch instead of once per point, leaving some 50
    point operations per scalar of its own. Bos-Coster has no fixed cost
    to share and settles at 44.5 per scalar, so few scalars is where the
    sharing pays and many is where the per-scalar figure is all there is.

    Cost here is a function of the bit length of the scalars and of
    nothing else, so no pair of magnitudes is pathological the way
    10**6 next to 1 is for a subtractive Bos-Coster step (issue 175).

    w=5 by measurement, on random 256-bit scalars: the table costs
    2^(w-2) - 1 additions and a doubling per point while the NAF has one
    nonzero digit in w+1, so the total falls to w=5 and rises again at
    w=6 (per scalar at 128 scalars: 57.7 operations at w=4, 53.3 at w=5,
    55.1 at w=6). In milliseconds over 10 scalars: 7.81 at w=4, 7.27 at
    w=5, 7.38 at w=6, 8.68 at w=7.

    No GLV splitting of its own, which would halve the doublings on
    secp256k1: the split is curve-specific, this function serves every
    curve, and with many scalars the doublings it would halve are already
    shared. A caller that has only two of them has the opposite balance,
    and curve_group_2's _double_mult_endomorphism_secp256k1_var is that
    caller: it splits both coefficients itself and hands the four halves
    here, so the split lives with the curve that has it and the
    interleaving stays one implementation.

    `fixed` is the points whose table is worth memoizing rather than
    building here: `ec._fixed_points`, or that set with the endomorphism's
    images added by the caller that forms them. A memoized table can be
    held at a width a per-call one could not pay for, `_FIXED_POINT_W`
    against the `w` every other point gets, and a wNAF has one nonzero
    digit in w+1, so the wide window is fewer additions in the loop. That
    is libsecp256k1's `WINDOW_G` of 15 beside its `WINDOW_A` of 5, on a
    table it generates at build time.

    Measured over 30 random 256-bit coefficient pairs, best of seven
    alternating rounds, memoized against built per call: 1.24x on
    `_double_mult_endomorphism_secp256k1_var`, whose four halves are two fixed
    points and two of the caller's, and 1.14x on `_double_mult_w_NAF_var` over
    secp256r1, which has one of each. With eight points of which one is
    the generator it is 1.05x, the fixed point being an eighth of the
    work. `_FIXED_POINT_W` is 10 by measurement on the first of those:
    1.07x at 4, 1.12x at 6, 1.15x at 8, 1.18x at 10, 1.20x at 12, against
    a table that doubles at every step -- and capped at `ec.scalar_len`,
    a window wider than the scalars buying nothing and costing a table.

    The input points are assumed to be on curve, the scalar coefficients
    are assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    # a number cannot be written in basis 1 (ie w=0)
    if w <= 0:
        raise BTClibValueError(f"non positive w: {w}")

    pairs = _multi_mult_pairs(scalars, jac_points)
    if not pairs:
        return INFJ

    # a point the caller hands the same on every call gets the memoized
    # table of _cached_odd_multiples_aff, at the wider window that only a
    # memoized table can pay for; every other point gets its own, built
    # here and dropped with the call
    # a window wider than the scalars themselves buys nothing and costs a
    # table, which is what the cap is for: the low-cardinality curves of
    # the test suite have a scalar_len of a handful of bits
    fixed_w = min(_FIXED_POINT_W, ec.scalar_len)
    nafs = []
    tables: list[list[Point]] = []
    # the tables this call has to build, kept in Jacobian coordinates
    # until they can be converted together
    pending: list[tuple[int, list[JacPoint]]] = []
    for i, (n, PJ) in enumerate(pairs):
        width = fixed_w if PJ in fixed else w
        nafs.append(_wNAF_of_m(n, width))
        if PJ in fixed:
            tables.append(_cached_odd_multiples_aff(PJ, ec, width))
        else:
            # a place in the list, filled by the conversion below
            tables.append([])
            pending.append((i, _odd_multiples(PJ, ec, width)))

    # one extended Euclid for every table the call builds, where a table
    # at a time is one apiece: the batch of `aff_from_jac_batch_var` over the
    # concatenation rather than over one point's share of it, which is
    # libsecp256k1's `secp256k1_ge_set_all_gej_var` over the whole of its
    # `pre_a`. An empty concatenation is not a case to test for: every
    # point being memoized leaves nothing to convert and nothing to do
    aff = ec.aff_from_jac_batch_var([P for _, jac in pending for P in jac])
    at = 0
    for i, jac in pending:
        tables[i] = aff[at : at + len(jac)]
        at += len(jac)

    # one doubling per position and the additions that position has:
    # `_additions_by_position` groups them this way rather than asking
    # every wNAF for a digit at every position, and is also where a
    # digit becomes the point it names
    R = INFJ
    for additions in reversed(_additions_by_position(nafs, tables, ec)):
        R = ec.double_jac(R)
        for P in additions:
            R = ec.add_jac_aff(R, P)
    return R


def _multi_mult_bos_coster_var(
    scalars: Sequence[int], jac_points: Sequence[JacPoint], ec: CurveGroup
) -> JacPoint:
    """Return the multi scalar multiplication u1*Q1 + ... + un*Qn.

    Use Bos-Coster's algorithm for efficient computation.

    A max-heap holds the (scalar, point) pairs still to be summed; each
    step pops the two largest scalars and rewrites their contribution as

        n1*P1 + n2*P2 = r*P1 + n2*(q*P1 + P2),  with n1 = q*n2 + r

    an identity, so the sum over the heap never changes: it is the
    invariant, and the single pair left at the end is the answer. The
    step also terminates, because r < n2 <= n1 makes the largest scalar
    strictly decrease, and r == 0 costs the heap an entry outright.

    Bos-Coster is usually written with the q == 1 case of that identity,
    n1*P1 + n2*P2 = (n1-n2)*P1 + n2*(P1+P2), which is Euclid by repeated
    subtraction: n1/n2 steps to do what one divmod does (issue 175) --
    multi_mult_var([10**6, 1], [G, H]) would take 10.6 s, and both
    multi_mult_var([n-1, 1], [G, H]) and multi_mult_var([-1, 1], [G, H]) would
    never finish, on scalars a caller has every right to pass. The whole
    of Euclid is what makes this a live path rather than a reading
    exercise: _multi_mult_var calls it above its threshold.

    Where the interleaved wNAF above shares one doubling per bit among
    all the points, this one has no fixed cost to amortize at all -- the
    heap converges towards scalars of the same size, and the quotient is
    1 about 40% of the time (Gauss-Kuzmin), so a step is usually one
    addition. That is why it wins on many scalars and loses on few: 44.5
    point operations per scalar over 128 random 256-bit scalars, against
    267.5 over two.

    The input points are assumed to be on curve, the scalar coefficients
    are assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    # source: https://cr.yp.to/badbatch/boscoster2.py
    pairs = _multi_mult_pairs(scalars, jac_points)
    if not pairs:
        return INFJ

    # a max-heap, which Python spells as a min-heap of negated scalars
    x: list[tuple[int, JacPoint]] = [(-n, PJ) for n, PJ in pairs]
    heapq.heapify(x)
    while len(x) > 1:
        np1 = heapq.heappop(x)
        np2 = heapq.heappop(x)
        n_1, p_1 = -np1[0], np1[1]
        n_2, p_2 = -np2[0], np2[1]
        # _mult_jac_var, not the faster _mult: the quotient is 1 about 40% of
        # the time (Gauss-Kuzmin), and _mult would rebuild its 16-entry
        # table of multiples for each of those -- 10x slower over 128
        # random scalars. _mult_jac_var(1, P) is P at no cost, so this is the
        # subtractive step precisely when the subtractive step is right;
        # measured, spelling that case out as a branch buys nothing, and
        # subtracting for q up to 4 or up to 16 costs 3% and 11%.
        q, n_1 = divmod(n_1, n_2)
        p_2 = ec.add_jac(_mult_jac_var(q, p_1, ec), p_2)
        if n_1 > 0:
            heapq.heappush(x, (-n_1, p_1))
        heapq.heappush(x, (-n_2, p_2))
    np1 = heapq.heappop(x)
    n_1, p_1 = -np1[0], np1[1]
    # n_1 is left as it is rather than reduced mod n: _mult reduces, and
    # the scalars reaching here are already below the order
    return _mult(n_1, p_1, ec)


# the number of nonzero scalars from which Bos-Coster is the cheaper of
# the two, measured here rather than borrowed: libsecp256k1 dispatches
# at 88, but it dispatches between other algorithms, on machine words,
# in C, and a number that has not been measured on Python integers is
# decoration.
# Best of five interleaved reps, random 256-bit scalars on secp256k1,
# Python 3.14, macOS arm64, wNAF over Bos-Coster: 0.91 at 40 scalars,
# 0.94 at 48, 1.000 at 56, 1.001 at 64, 1.04 at 72, 1.09 at 96. The two
# meet at 56, so 56 it is; anywhere in 56..64 measures the same, and the
# cost of being wrong by a dozen scalars either way is under 1%.
BOS_COSTER_THRESHOLD = 56


def _multi_mult_var(
    scalars: Sequence[int], jac_points: Sequence[JacPoint], ec: CurveGroup
) -> JacPoint:
    """Return the multi scalar multiplication u1*Q1 + ... + un*Qn.

    Interleaved wNAF up to BOS_COSTER_THRESHOLD nonzero scalars and
    Bos-Coster from there on, the two crossing where the shared doublings
    stop paying for themselves (issue 212). Both are kept, and not only to
    be dispatched between: the library is didactic as much as it is a
    library, and Bos-Coster is the one that can be read in twenty lines.

    Pippenger, the third algorithm libsecp256k1 has, is *not* here, and
    the measurement is the reason. Prototyped with sparse buckets and the
    running-sum trick, best window per size, it lost at every size tried:
    against Bos-Coster in ms, 162 vs 125 at 256 scalars, 284 vs 225 at
    512, 500 vs 406 at 1024. Its bucket sums are additions of points that
    cost the same as any other addition in Python, where in C they are
    the cheap part, so the crossover it has there is beyond any batch
    btclib is asked to verify -- and a threshold nobody reaches is a
    branch nobody takes.

    The zeros are counted out before the dispatch rather than left to
    len(), because a zero scalar is dropped downstream and the batch that
    reaches either implementation is the nonzero one: 56 scalars of which
    2 are nonzero is a batch of two, and sending it to Bos-Coster on its
    length costs 1.81 ms against the wNAF's 1.02. The pass that counts
    them is 0.8 us at that size, under a thousandth of either.

    The input points are assumed to be on curve, the scalar coefficients
    are assumed to have been reduced mod n if appropriate (e.g. cyclic
    groups of order n).
    """
    if sum(1 for n in scalars if n) < BOS_COSTER_THRESHOLD:
        return _multi_mult_w_NAF_var(
            scalars, jac_points, ec, _MULTI_MULT_W, ec._fixed_points
        )
    return _multi_mult_bos_coster_var(scalars, jac_points, ec)
