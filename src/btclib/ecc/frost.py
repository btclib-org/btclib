"""FROST threshold Schnorr signing, according to BIP445.

https://github.com/bitcoin/bips/pull/2070, `bip-0445.md` at v0.10.0,
head `8e25d579` on `siv2r:bip-frost-signing`. The BIP is a draft and not
in `bitcoin/bips` `master`; `tests/_data/README.md` records why v0.10.0
is where this module pins.

FROST turns *t* of *n* participants into one signer: a threshold secret
key is Shamir-shared among *n* participants at key generation, and any
*t* of them can cooperatively produce a signature that verifies under a
single x-only public key with `btclib.ecc.ssa` and with any other BIP340
verifier -- the same output shape `btclib.ecc.musig2` produces for an
*n*-of-*n* group, with a chosen subset standing in for the whole group.

**Key generation is out of scope, here as in the BIP.** This module
takes a threshold secret key already split into shares -- a *secshare*
per participant, all of them scalar multiples of the same secret
polynomial's constant term -- and never splits one itself. The vectors
this module is tested against are generated by a trusted dealer, and
`validate_threshold_info` checks key material a dealer or a DKG produced
rather than producing any: it asks whether a threshold info's own public
shares reconstruct its own threshold public key, which functional
compatibility needs and which is not a statement about how that key
material came to exist. `btclib-org/btclib#257` is where interactive
threshold signing is tracked; it stays open, `upstream-dependent`, and is
the hook that brings key generation and ChillDKG back once BIP445 or
BIP-FROST-DKG settle further.

The round shape mirrors `btclib.ecc.musig2`: a primitive per round and no
function that signs, because signing is interactive. Key material and
nonces come from the caller, not from a session this module holds:

- setup, once per group: `validate_threshold_info` on the *n*-participant
  `ThresholdInfo` a dealer or a DKG produced;
- tweaking, optional and once per session: `tweak_ctx_init` and
  `apply_tweak`, or `thresh_pubkey_and_tweak` for both in one call,
  answering a `TweakContext`;
- round 1, the nonces: `nonce_gen` for each of the *u* selected signers,
  then `nonce_agg` over what they published, which anyone can do;
- round 2, the partial signatures: `sign` (or `deterministic_sign`) for
  each signer, `partial_sig_verify` to hold a signer to what it sent, and
  `partial_sig_agg` for the aggregate signature.

**A secret nonce signs once**, exactly as in `musig2`: `sign` zeroes the
64-byte bytearray it is given before using it, so calling it twice with
the same buffer reads two zero scalars and raises rather than signing
twice -- which is why its argument is a `bytearray` and not `bytes`.

**Participant vs. signer.** *n* participants exist from key generation
on, each with an identifier in `0 .. n-1`, a *secshare* and a *pubshare*.
A signing session selects *u* of them, *t <= u <= n*; that subset is the
*signers*, and every `ids` argument below names their identifiers,
sorted or not as the caller built the list. `ThresholdInfo.pub_shares`
is indexed by identifier over all *n* participants and may hold `None`
where a share is unknown; a `SessionContext`'s own `pub_shares`, when
given at all, is the *u*-long list for the selected signers alone --
absent entirely is also valid, a signer able to produce and verify
against its own partial signature without it, `partial_sig_verify`
alone requiring the list because there is no other way to check a
signature against a key it was not given.

secp256k1 and sha256 are not parameters here, unlike everywhere else in
`btclib.ecc`, for the reason `musig2`'s own docstring gives: BIP445 is
defined for that pair alone, and a `Curve` argument would advertise a
genericity no vector could check.

The upper bound of 128 participants (`n <= 128`) is a security
requirement and not a format one: FROST3's unforgeability proof assumes
the set of compromised participants is fixed before key generation, and
an adversary that instead chooses whom to compromise after seeing the
public shares can, for large *n*, forge with fewer than *t* compromised
participants -- provided it solves a search problem BIP445 cites as
provably hard whenever *n <= 131*. 128 stays inside that bound with a
margin; it is not raised by passing a larger *n* to any function here.

The tags below are BIP445's own and disjoint from BIP327's: `BIP0445/aux`,
`BIP0445/nonce`, `BIP0445/noncecoef` and `BIP0445/deterministic/nonce`.
Only `BIP0340/challenge` is shared, and it is BIP340's, read the same way
`musig2` reads it -- through `btclib.ecc.ssa.challenge_`.

**Nothing here is shared with `btclib.ecc.musig2` by import**, though
BIP445's own reference code says in its header that it is "copied or
modified from" BIP327's: this module's tag bytes, several error
messages (the tweak-range message among them) and the shape of
`ThresholdInfo`/interpolation differ from BIP327's, and the
functions that do look alike -- `nonce_agg`, `apply_tweak` -- were
checked line by line against BIP445's own reference rather than assumed
identical from the name. Where a check found the same construction, this
module keeps its own copy rather than importing `musig2`'s private
helpers: the two modules are each a self-contained mirror of one BIP,
which is the shape `musig2.py` itself already has no sibling to share
with.
"""

