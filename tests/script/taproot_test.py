def test_the_two_output_keys_are_one_tweak() -> None:
    """A tree and its own merkle root reach the same output key.

    Which is the whole claim of `output_pubkey_from_merkle_root`: it is
    `output_pubkey` with the root already computed, the form a psbt
    carries it in. Both halves of BIP341's tweak are checked -- the key
    path, where the root is empty, and a tree, whose root comes from
    `tree_helper`.

    The unspendable internal key `output_pubkey` substitutes for a
    missing one is not this function's business: the psbt field it
    serves is either present or the input says nothing to check.
    """
    internal_pubkey = mult(123456)
    x_only = bytes_from_point(internal_pubkey)[1:]
    assert output_pubkey_from_merkle_root(x_only) == output_pubkey(internal_pubkey)

    script_tree: TaprootScriptTree = [[(0xC0, ["OP_2"])], [(0xC0, ["OP_3"])]]
    merkle_root = tree_helper(script_tree)[1]
    assert output_pubkey_from_merkle_root(x_only, merkle_root) == (
        output_pubkey(internal_pubkey, script_tree)
    )

    # a memoryview x, which `bytes_from_octets` coerces: `memoryview +
    # bytes` is not an operation at all, and this function prefixes an
    # `02` to the x it was given. The internal key of `output_pubkey`
    # passes the same coercion one layer lower, in `PubKeyData`, so this
    # entry point needs its own assertion rather than that one's
    assert output_pubkey_from_merkle_root(memoryview(x_only), merkle_root) == (
        output_pubkey(internal_pubkey, script_tree)
    )


def test_the_two_output_prvkeys_are_one_tweak() -> None:
    """A tree and its own merkle root tweak a private key the same way.

    The private counterpart of `test_the_two_output_keys_are_one_tweak`:
    a `KeyManager` signing a taproot key path spend has the merkle root
    a psbt carries and not the tree that produced it, and this is what
    tweaks a private key from the one it is given.
    """
    prv_key = 123456
    assert output_prvkey_from_merkle_root(prv_key) == output_prvkey(prv_key)

    script_tree: TaprootScriptTree = [[(0xC0, ["OP_2"])], [(0xC0, ["OP_3"])]]
    merkle_root = tree_helper(script_tree)[1]
    assert output_prvkey_from_merkle_root(prv_key, merkle_root) == output_prvkey(
        prv_key, script_tree
    )


# the vector's scriptTree, not a tree: nested json lists of
# {"leafVersion": ..., "script": ...} objects, hence Any in and a real
# TaprootScriptTree out -- each leaf a tuple, the one shape the alias
# names, not a two-element list that happens to unpack the same way
def convert_script_tree(script_tree: Any) -> TaprootScriptTree:
    """Convert a vector's scriptTree json into a TaprootScriptTree."""
    if isinstance(script_tree, list):
        return [convert_script_tree(x) for x in script_tree]
    if isinstance(script_tree, dict):
        return [(script_tree["leafVersion"], parse(script_tree["script"]))]
    return []


